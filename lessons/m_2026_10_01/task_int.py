def time_detector(seconds=None):
    if not seconds:
        print("значение НЕ передано")
        return
    hours = seconds // (60 * 60)
    minutes = seconds // 60 % 60
    secs = seconds % 60
    print(hours, "ч", minutes, "мин", secs, "сек")

